const {Router}=require('express')
const {rateLimit}=require('express-rate-limit')
const leads=require('../controllers/leads')
const auth=require('../controllers/auth')
const admin=require('../controllers/admin')
const {requireAuth,requireCsrf}=require('../middlewares/auth')
const router=Router()
const quoteLimiter=rateLimit({windowMs:15*60*1000,limit:8,standardHeaders:'draft-7',legacyHeaders:false,message:{message:'Muitas tentativas. Aguarde alguns minutos.'}})
const loginLimiter=rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:'draft-7',legacyHeaders:false,message:{message:'Muitas tentativas. Aguarde alguns minutos.'}})
router.get('/health',(req,res)=>res.json({status:'ok'}))
router.post('/v1/leads',quoteLimiter,leads.create)
router.post('/v1/auth/login',loginLimiter,auth.login)
router.get('/v1/auth/me',auth.me)
router.post('/v1/auth/logout',requireAuth,requireCsrf,auth.logout)
router.use('/v1/admin',requireAuth)
router.get('/v1/admin/summary',admin.summary)
router.get('/v1/admin/leads/export',admin.export)
router.get('/v1/admin/leads',admin.list)
router.get('/v1/admin/leads/:id',admin.detail)
router.patch('/v1/admin/leads/:id',requireCsrf,admin.update)
router.delete('/v1/admin/leads/:id',requireCsrf,admin.remove)
module.exports=router
